require "digest"
class ContentRepository
  POST_CATEGORIES = { "comm" => %w[GAME_THREAD GENERAL TRADE_RUMORS FREE MARKET MEETUP NOTICE NEWS], "column" => ["COLUMN"], "analysis" => ["ANALYSIS"], "community" => %w[GAME_THREAD GENERAL TRADE_RUMORS FREE MARKET MEETUP NOTICE NEWS COLUMN ANALYSIS] }.freeze

  def initialize(database: nil, cache: Rails.cache)
    @database = database || Records::Database.default
    @cache = cache
    @namespace = Digest::SHA256.hexdigest(ENV["DATABASE_URL"].to_s)
  end

  def list(kind, page: 1)
    raise ArgumentError unless kind == "news" || POST_CATEGORIES.key?(kind)
    cached(["list", kind, page]) do
      offset = (page - 1) * 30
      if kind == "news"
        @database.read(<<~SQL, [offset])
          SELECT id,COALESCE("titleKr",title) AS title,COALESCE("summaryKr",summary,'') AS summary,"imageUrl","publishedAt" AS date
          FROM public."News" WHERE published=true AND "retractedAt" IS NULL AND (team IS NULL OR team<>'wings')
          ORDER BY "publishedAt" DESC,id DESC LIMIT 31 OFFSET $1
        SQL
      else
        @database.read(<<~SQL, ["{#{POST_CATEGORIES.fetch(kind).join(',')}}", offset])
          SELECT p.id,p.title,p.category,p."createdAt" AS date,p."updatedAt",u.username,u.name,
            (SELECT count(*)::integer FROM public."Comment" c WHERE c."postId"=p.id) AS comments
          FROM public."Post" p JOIN public."User" u ON u.id=p."authorId"
          WHERE p.category::text=ANY($1::text[]) ORDER BY p."createdAt" DESC,p.id DESC LIMIT 31 OFFSET $2
        SQL
      end
    end
  end

  def article(kind, id)
    cached(["article", kind, id]) do
      rows = if kind == "news"
        @database.read(<<~SQL, [id])
          SELECT id,COALESCE("titleKr",title) AS title,COALESCE("contentKr",content) AS content,COALESCE("summaryKr",summary,'') AS summary,
            "imageUrl","publishedAt" AS date,"crawledAt" AS updated,"sourceUrl",source,author,"autoGenerated"
          FROM public."News" WHERE id=$1 AND published=true AND "retractedAt" IS NULL AND (team IS NULL OR team<>'wings')
        SQL
      else
        categories = POST_CATEGORIES.fetch(kind, [])
        @database.read(<<~SQL, [id, "{#{categories.join(',')}}"])
          SELECT p.id,p.title,p.content,p.category,p."createdAt" AS date,p."updatedAt" AS updated,p.images,p."snsLinks",
            u.username,COALESCE(u.name,u.username) AS author,p."isLocked",p."price",p."meetupLocation",p."meetupDate"
          FROM public."Post" p JOIN public."User" u ON u.id=p."authorId" WHERE p.id=$1 AND p.category::text=ANY($2::text[])
        SQL
      end
      next nil if rows.empty?
      article = rows.first
      article["comments"] = @database.read(<<~SQL, [id]) unless kind == "news"
        SELECT c.id,c.content,c."createdAt" AS date,COALESCE(u.name,u.username) AS author,c."parentId"
        FROM public."Comment" c JOIN public."User" u ON u.id=c."authorId" WHERE c."postId"=$1 ORDER BY c."createdAt",c.id
      SQL
      article
    end
  end

  def index
    cached(["index"]) do
      @database.read(<<~SQL)
        SELECT id,'news' AS kind,"crawledAt" AS updated FROM public."News"
        WHERE published=true AND "retractedAt" IS NULL AND (team IS NULL OR team<>'wings')
        UNION ALL SELECT id,CASE WHEN category='COLUMN' THEN 'column' WHEN category='ANALYSIS' THEN 'analysis' ELSE 'community' END AS kind,"updatedAt" AS updated FROM public."Post"
      SQL
    end
  end

  private
  def cached(key, &block)
    @cache.fetch(["content-v2", @namespace, *key], expires_in: 60, skip_nil: true, &block)
  end
end
